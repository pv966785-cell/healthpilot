import { LabTest } from './types';

/**
 * Constant baseline markup percentage applied to lab rates.
 * Patient-facing price = round(labRate * (1 + PRICE_MARKUP_PERCENT / 100))
 */
export const PRICE_MARKUP_PERCENT = 0;

/**
 * Calculates patient-facing price from lab rate and markup percentage.
 */
export function getPatientPrice(labRate: number, markupPercent: number = PRICE_MARKUP_PERCENT): number {
  return Math.round(labRate * (1 + markupPercent / 100));
}

/**
 * Formats price in Indian Rupee format (e.g. ₹1,499)
 */
export function formatINR(amount: number): string {
  return '₹' + amount.toLocaleString('en-IN');
}

